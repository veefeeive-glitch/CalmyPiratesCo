"""Export desktop-fly data/circuit.json to one immutable C++ CSR graph.

Python standard library only. Preserve neuron indices and edge order within rows.
Usage: python Scripts/export_fly_connectome.py PATH/TO/desktop-fly
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

PIN = "32b00011e83c3dc85fa3ea0b3934155b04f1635d"


def export(repo, output):
    revision = subprocess.check_output(["git", "-C", str(repo), "rev-parse", "HEAD"], text=True).strip()
    if revision != PIN:
        raise ValueError(f"Expected {PIN}, got {revision}; review upstream before changing PIN")
    raw = (repo / "data/circuit.json").read_bytes()
    if hashlib.sha256(raw).hexdigest() != "da53640e4dc7071c26892870ec5b28984c4cfc74c1c44d3a3cde0a2913579d0f":
        raise ValueError("circuit.json differs from the reviewed pinned source")
    data = json.loads(raw)
    neurons, edges = data["neurons"], data["edges"]
    if len(neurons) != 668 or len(edges) != 18968:
        raise ValueError("Unexpected circuit size")
    if len({n["id"] for n in neurons}) != 668:
        raise ValueError("Duplicate neuron IDs")
    groups = {name: [] for name in ["LoomLeft", "LoomRight", "GF", "DNaLeft", "DNaRight", "MDN", "Forward", "Groom", "Wing", "Ascending", "Sensory"]}
    roles, senses, baselines = [], [], []
    rng = 783  # Frozen heterogeneous excitability, shared by all flies.
    for i, n in enumerate(neurons):
        r, side = n["role"], n["side"]
        group, code, sense = None, 0, 0
        if r in ("lc4", "lplc2"):
            group, code, sense = ("LoomLeft" if side == "left" else "LoomRight"), 1, (1 if side == "left" else 2)
        elif r in ("dna01", "dna02"):
            group, code = ("DNaLeft", 2) if side == "left" else ("DNaRight", 3)
        elif r in ("mdn", "dnp09", "dng11", "escw", "gf"):
            group, code = {"mdn": ("MDN", 4), "dnp09": ("Forward", 5), "dng11": ("Groom", 6), "escw": ("Wing", 7), "gf": ("GF", 8)}[r]
        elif r == "other" and n["type"] in ("ascending", "sensory"):
            group = "Ascending" if n["type"] == "ascending" else "Sensory"
        if group:
            groups[group].append(i)
        rng = (1664525 * rng + 1013904223) & 0xffffffff
        base = 0.010 + rng / 4294967296 * 0.060 if r == "other" else 0.004 if code == 1 else 0.038 if code == 5 else 0.036 if code in (2, 3, 4, 6, 7) else 0.002
        roles.append(code)
        senses.append(sense)
        baselines.append(base)
    rows = [[] for _ in neurons]
    for pre, post, signed_count in edges:
        if not isinstance(pre, int) or not isinstance(post, int) or not 0 <= pre < 668 or not 0 <= post < 668:
            raise ValueError("Invalid edge endpoint")
        if not isinstance(signed_count, (int, float)) or not __import__("math").isfinite(signed_count):
            raise ValueError("Invalid weight")
        n = neurons[pre]
        electrical = n["role"] in ("lc4", "lplc2") or (n["role"] == "other" and n["type"] == "sensory")
        weight = signed_count * 0.0008 * (6 if electrical and neurons[post]["role"] == "gf" else 1)
        rows[pre].append((post, weight))
    starts, cols, weights = [0], [], []
    for row in rows:
        cols.extend(e[0] for e in row)
        weights.extend(e[1] for e in row)
        starts.append(len(cols))
    counts = [roles.count(i) for i in range(9)]
    digest = hashlib.sha256(raw).hexdigest()
    lines = ["// GENERATED by Scripts/export_fly_connectome.py; do not edit.",
             f"// desktop-fly {PIN}; circuit.json SHA256 {digest}",
             "// FlyWire FAFB v783 / CC BY-NC 4.0. See SourceAssets/ThirdParty/DesktopFly/README.md.",
             "// Only FlySwarmMob.cpp includes this file: a single graph in the module.",
             "namespace FlyConnectomeData", "{"]
    def array(kind, name, values, floats=False):
        def fmt(x):
            s = format(x, ".9g")
            return (s if "." in s or "e" in s else s + ".0") + "f" if floats else str(x)
        lines.append(f"static constexpr {kind} {name}[] = {{")
        for j in range(0, len(values), 16):
            lines.append("    " + ", ".join(fmt(v) for v in values[j:j+16]) + ",")
        lines.append("};")
    array("uint32", "RowStart", starts)
    array("uint16", "Targets", cols)
    array("float", "Weights", weights, True)
    array("float", "Baseline", baselines, True)
    array("uint8", "Role", roles)
    array("uint8", "SensorSide", senses)
    array("uint16", "GroupCount", counts)
    for name, indices in groups.items():
        array("uint16", name, indices)
    lines.append("}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest = {"revision": revision, "sha256": digest, "neurons": len(neurons), "edges": len(edges), "excitatory_rows": sum(e[2] > 0 for e in edges), "inhibitory_rows": sum(e[2] < 0 for e in edges), "groups": groups, "index_to_neuron": neurons}
    output.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in manifest.items() if k not in ("groups", "index_to_neuron")}))
    print(json.dumps(groups))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repository", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "Source/CalmyPiratesCo/Private/Gameplay/FlyConnectomeData.inl")
    args = parser.parse_args()
    export(args.repository, args.output)
